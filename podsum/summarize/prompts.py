"""Prompts for Russian IT podcasts.

Written in Russian on purpose: instructions in the same language as the source
keep models from drifting into English mid-summary, and the domain wording
("техдолг", "прод", "релиз") primes the right register.
"""

from __future__ import annotations

LANGUAGE_NAMES = {"ru": "русском", "en": "английском"}

SYSTEM = """Ты — редактор технического подкаста об IT и разработке.
Ты работаешь с расшифровкой живой речи: в ней есть оговорки, повторы, обрывы фраз
и ошибки распознавания английских терминов. Твоя задача — вытащить смысл, а не пересказать слова.

Правила:
- Пиши на {language} языке. Названия технологий оставляй в оригинальном написании (Kubernetes, Kafka, PostgreSQL).
- Опирайся только на расшифровку. Ничего не додумывай и не добавляй общеизвестные факты, которых в записи нет.
- Если распознавание явно исказило термин, восстанови его по контексту (например, «кубернетис» → Kubernetes).
- Конкретика важнее общих слов: цифры, версии, названия инструментов, принятые решения и их причины.
- Отвечай строго валидным JSON без markdown-обёртки и без комментариев."""

MAP_INSTRUCTIONS = """Перед тобой фрагмент расшифровки подкаста ({position} из {total}).
Каждая строка начинается с тайм-кода [чч:мм:сс].

Сделай подробные заметки по этому фрагменту. Не пиши вводных фраз, только JSON:

{{
  "topics": [
    {{
      "title": "краткое название темы",
      "timestamp": "чч:мм:сс — где тема начинается",
      "points": ["тезис 1", "тезис 2"],
      "detail": "2-4 предложения: контекст, аргументы, к чему пришли"
    }}
  ],
  "tech": [
    {{"name": "Kafka", "what": "что это одной строкой", "context": "в каком контексте упомянули"}}
  ],
  "quotes": [
    {{"text": "дословная цитата", "timestamp": "чч:мм:сс"}}
  ],
  "takeaways": ["практический вывод, который слушатель может применить"],
  "open_questions": ["спорный момент или вопрос без ответа"]
}}

Требования:
- Тайм-коды бери из фрагмента, не выдумывай.
- Пустые списки допустимы, если во фрагменте нечего извлечь.
- Реклама, джинглы и оргмоменты («ставьте лайк», «наш спонсор») — пропускай.

Фрагмент:
---
{chunk}
---"""

REDUCE_INSTRUCTIONS = """Ниже — заметки по всем фрагментам одного выпуска подкаста, в хронологическом порядке.
Собери из них цельную сводку выпуска. Убери дубли: одна тема должна встречаться один раз,
с самым ранним тайм-кодом.

Верни строго такой JSON:

{schema}

Требования:
- "tldr": {tldr_min}-{tldr_max} пунктов. Это самый верхний уровень: о чём выпуск и что из него следует. Без тайм-кодов.
- "topics": глубокий разбор. Для каждой темы — контекст, позиции участников, к какому выводу пришли.
- "chapters": хронология всего выпуска, 5-12 пунктов, тайм-коды по возрастанию.
- Ничего не добавляй сверх заметок.

Заметки:
---
{notes}
---"""

SINGLE_PASS_INSTRUCTIONS = """Перед тобой полная расшифровка выпуска подкаста.
Каждая строка начинается с тайм-кода [чч:мм:сс].

Сделай сводку выпуска на двух уровнях: короткое резюме и подробный разбор.
Верни строго такой JSON:

{schema}

Требования:
- "tldr": {tldr_min}-{tldr_max} пунктов, читается за 30 секунд, без тайм-кодов.
- "topics": подробный разбор по темам — контекст, аргументы сторон, разногласия, выводы.
- "tech": все упомянутые технологии и инструменты с пояснением, зачем о них зашла речь.
- "chapters": хронология выпуска, 5-12 пунктов, тайм-коды по возрастанию.
- Тайм-коды бери из расшифровки, не выдумывай.
- Реклама и оргмоменты в сводку не попадают.

Расшифровка:
---
{transcript}
---"""

SUMMARY_SCHEMA = """{
  "title": "название выпуска одной строкой",
  "tldr": ["короткий тезис"],
  "topics": [
    {
      "title": "название темы",
      "timestamp": "чч:мм:сс",
      "points": ["ключевой тезис"],
      "detail": "развёрнутый разбор: контекст, аргументы, вывод"
    }
  ],
  "tech": [
    {"name": "Kubernetes", "what": "что это", "context": "зачем упомянули"}
  ],
  "takeaways": ["что слушателю стоит попробовать или проверить у себя"],
  "debates": [
    {"question": "спорный вопрос", "positions": ["позиция одной стороны", "позиция другой"]}
  ],
  "quotes": [{"text": "дословная цитата", "timestamp": "чч:мм:сс"}],
  "chapters": [{"timestamp": "чч:мм:сс", "title": "что происходит"}]
}"""

TLDR_MIN, TLDR_MAX = 5, 7


def system_prompt(output_lang: str = "ru") -> str:
    return SYSTEM.format(language=LANGUAGE_NAMES.get(output_lang, "русском"))


def map_prompt(chunk: str, position: int, total: int) -> str:
    return MAP_INSTRUCTIONS.format(chunk=chunk, position=position, total=total)


def reduce_prompt(notes: str) -> str:
    return REDUCE_INSTRUCTIONS.format(
        notes=notes, schema=SUMMARY_SCHEMA, tldr_min=TLDR_MIN, tldr_max=TLDR_MAX
    )


def single_pass_prompt(transcript: str) -> str:
    return SINGLE_PASS_INSTRUCTIONS.format(
        transcript=transcript, schema=SUMMARY_SCHEMA, tldr_min=TLDR_MIN, tldr_max=TLDR_MAX
    )
